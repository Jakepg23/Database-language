FUNCTION FIDE_VALIDAR_FACTURA_PARA_MATRICULA_FN (
    P_ID_FACTURA IN NUMBER
) RETURN NUMBER
IS
V_VALIDACION NUMBER := 0;

CURSOR ENCABEZADO IS SELECT * FROM FIDE_ENCABEZADO_FACTURA_TB 
WHERE ID_FACTURA = P_ID_FACTURA AND ID_ESTADO = 3;

CURSOR DETALLE IS SELECT ID_SERVICIO FROM FIDE_DETALLE_FACTURA_TB 
WHERE ID_FACTURA = P_ID_FACTURA;

BEGIN
FOR I IN ENCABEZADO LOOP
V_VALIDACION := 1;
EXIT;
END LOOP;

IF V_VALIDACION = 0 THEN RETURN 0;
END IF;

V_VALIDACION := 0;
FOR D IN DETALLE LOOP
IF D.ID_SERVICIO = 1 THEN V_VALIDACION := 1;
EXIT;
END IF;
END LOOP;
RETURN V_VALIDACION;
 
EXCEPTION WHEN OTHERS THEN RETURN -1;
END FIDE_VALIDAR_FACTURA_PARA_MATRICULA_FN;

