--VISTA 5 — ACTIVIDADES 
CREATE OR REPLACE VIEW FIDE_AUDITORIA_ACTIVIDADES_V AS
SELECT
    A.ID_AUDITORIA,
    A.ACCION,
    A.FECHA_ACCION,
    A.USUARIO,
    AC.ID_ACTIVIDAD,
    AC.DESCRIPCION,
    AC.FECHA,
    AC.HORA,
    AC.FECHA_CREACION,
    AC.FECHA_MODIFICACION,
    AC.CREADO_POR,
    AC.MODIFICADO_POR
